#!/usr/bin/env python3
"""Generate supabase/migrations/0005_seed_courses.sql from courses.json.

courses.json stays the roster's source of truth. This keeps the database in
step with it without anyone hand-typing 15 rows.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
COURSES = json.loads((ROOT / "courses.json").read_text())["courses"]

# Clubs that make you create a free public-member account before checkout.
REQUIRES_REGISTRATION = {"bayview"}


def q(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


rows = []
for i, c in enumerate(COURSES):
    host = c.get("host") or f"{c['slug']}.miclub.com.au"
    rows.append(
        "  ({slug}, {name}, {region}, {host}, {fee}, {drive}, {holes}, {par}, "
        "{reg}, {addr}, {notes}, {order})".format(
            slug=q(c["slug"]),
            name=q(c["name"]),
            region=q(c.get("region", "")),
            host=q(host),
            fee=q(str(c["feeGroupId"])),
            drive=q(c.get("drive_minutes_from_bondi")),
            holes=q(c["holes"]),
            par=q(c.get("par")),
            reg=q(c["slug"] in REQUIRES_REGISTRATION),
            addr=q(c.get("address")),
            notes=q(c.get("notes", "")),
            order=q(i),
        )
    )

sql = """-- Tees for the Boys — course roster.
--
-- GENERATED by scripts/gen_seed.py from courses.json. Do not hand-edit: change
-- courses.json and regenerate.
--
-- The roster is FROZEN at {n} courses for this version. length_metres is
-- deliberately absent — MiClub does not publish it and we do not invent it.

insert into public.courses
  (slug, name, region, host, fee_group_id, drive_minutes_from_bondi, holes, par,
   requires_registration, address, notes, sort_order)
values
{rows}
on conflict (slug) do update set
  name                     = excluded.name,
  region                   = excluded.region,
  host                     = excluded.host,
  fee_group_id             = excluded.fee_group_id,
  drive_minutes_from_bondi = excluded.drive_minutes_from_bondi,
  holes                    = excluded.holes,
  par                      = excluded.par,
  requires_registration    = excluded.requires_registration,
  address                  = excluded.address,
  notes                    = excluded.notes,
  sort_order               = excluded.sort_order,
  updated_at               = now();
""".format(n=len(COURSES), rows=",\n".join(rows))

out = ROOT / "supabase" / "migrations" / "0005_seed_courses.sql"
out.write_text(sql)
print(f"wrote {out} — {len(COURSES)} courses")
